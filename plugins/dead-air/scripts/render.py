SHOW_JS = "(k) => { window.__groups.forEach((g, i) => g.forEach(e => e.style.visibility = i < k ? 'visible' : 'hidden')); }"

# Seconds per Reel slide (about 42 s in all, close to the Oct 22 Board of Peace cut Imran liked).
# Lines appear one at a time inside each slide's budget; the finished slide holds for 2 s.
REEL_BUDGET = {"hook": 5, "timeline": 12, "claims": 11, "receipt": 8, "family": 8, "closer": 6,
               # Update Reels (addendum v2.1 §B): fixed holds, about 20 s. `update_closer` is the addendum's
               # "closer 4", kept apart so the deep Reels' 6 s Closer doesn't change.
               "update_then": 6, "update_square": 1.5, "update_hold": 4, "update_closer": 4}
# A family slide that opens the Reel holds its last frame "a couple of seconds too long" (Imran, Oct 31).
OPEN_FAMILY = {"budget": 13, "final": 5.5}

def holds_for(words, budget, final=2.0):
    floor = 0.8
    spread = max(budget - final, floor * len(words))
    tot = sum(words) or 1
    hs = [max(floor, spread * w / tot) for w in words]
    hs[-1] += final
    return [round(h, 2) for h in hs]

def _opt(a, flag):
    if flag not in a: return None
    i = a.index(flag)
    if i + 1 >= len(a) or a[i + 1].startswith("--"): raise SystemExit(f"{flag} needs a value")
    return a[i + 1]

def default_fonts():
    """First @fontsource folder found: next to this script, then the working dir, then ./dead-air (SPEC §4.2-3)."""
    cands = [Path(__file__).resolve().parent / "node_modules/@fontsource",
             Path("node_modules/@fontsource"), Path("dead-air/node_modules/@fontsource")]
    return str(next((c for c in cands if c.is_dir()), cands[0]))

def _secs(flag, v):
    try: return float(v)
    except ValueError: raise SystemExit(f"{flag}: '{v}' is not a number of seconds")

def parse_budget(spec):
    out = {}
    for part in spec.split(","):
        k, _, v = part.partition("=")
        k = k.strip()
        if k not in REEL_BUDGET: raise SystemExit(f"--budget: unknown slide '{k}' (use {', '.join(REEL_BUDGET)})")
        out[k] = _secs("--budget", v)
    return out

def post_stem(post):
    """Output file stem. An update adds its slug, so two Updates on one day never share file names."""
    s = f"schmimknews-{post['date']}-{post['format']}"
    return f"{s}-{post['slug']}" if post["format"] == "update" else s

def main():
    a = sys.argv[1:]
    if len(a) < 3: print(__doc__); sys.exit(2)
    post_p, ddir, out = Path(a[0]), Path(a[1]), Path(a[2])
    fdir = _opt(a, "--fonts") or default_fonts()
    only = _opt(a, "--only")
    if only not in (None, "reel", "carousel"): raise SystemExit("--only must be reel or carousel")
    budget, open_family = dict(REEL_BUDGET), dict(OPEN_FAMILY)
    if (v := _opt(a, "--budget")): budget.update(parse_budget(v))
    if (v := _opt(a, "--open-family")):
        b, _, fin = v.partition(",")
        open_family.update(budget=_secs("--open-family", b), final=_secs("--open-family", fin) if fin else open_family["final"])
    post = json.loads(post_p.read_text())
    errs = check_copy(post)
    if errs:
        print("COPY CHECK FAILED:"); [print(" -", e) for e in errs]; sys.exit(1)
    tokens = json.loads((ddir / "project/tokens.json").read_text())
    css = fonts_css(fdir) + tokens_css(tokens) + (ddir / "project/components/bundle.css").read_text() + "body{margin:0;background:#000}"
    out.mkdir(parents=True, exist_ok=True)
    slides, reels = build_slides(post), reel_slides(post, budget)
    if only != "reel" and len(post.get("alt", [])) != len(slides):
        print(f"COPY CHECK FAILED:\n - alt needs {len(slides)} strings, one per slide"); sys.exit(1)
    stem = post_stem(post)
    fdir_frames = out / ".reel-frames"; fdir_frames.mkdir(exist_ok=True)
    # Clear what this run is about to write, so a re-render with fewer slides or steps leaves nothing stale behind.
    stale = []
    if only != "reel": stale += list(out.glob(f"{stem}-[0-9][0-9].png"))
    if only != "carousel": stale += [out / f"{stem}-reel.mp4", out / f"{stem}-reel-cover.png"] + list(fdir_frames.glob("*"))
    for f in stale: f.unlink(missing_ok=True)
    from playwright.sync_api import sync_playwright
    problems, files, frames = [], [], []
    with sync_playwright() as p:
        b = p.chromium.launch()
        passes = []
        if only != "reel": passes.append(("slide", slides))
        # An update's Reel opens on its Then slide, so its cover is carousel slide 1: copied below, or rendered on its own with --only reel.
        if only == "reel" and post["format"] == "update": passes.append(("cover", slides[:1]))
        if only != "carousel": passes.append(("reel", reels))
        for kind, items in passes:
            for i, item in enumerate(items, 1):
                static = isinstance(item, tuple)
                body = item[0] if static else item
                pg = b.new_page(viewport={"width": 1080, "height": 1350})
                doc = f'<!doctype html><html lang="en"><head><meta charset="utf-8"><style>{css}</style></head><body>{body}</body></html>'
                tmp = out / f".tmp-{kind}-{i}.html"; tmp.write_text(doc)
                pg.goto(tmp.resolve().as_uri()); pg.evaluate("document.fonts.ready"); pg.wait_for_timeout(150)
                for prob in pg.evaluate(MEASURE_JS): problems.append(f"{kind} {i}: {prob}")
                if kind == "slide":
                    name = f"{stem}-{i:02d}.png"
                    pg.locator(".slide").screenshot(path=str(out / name)); files.append(name)
                elif kind == "cover":
                    name = f"{stem}-reel-cover.png"
                    pg.locator(".slide").screenshot(path=str(out / name)); files.append(name)
                elif static:
                    fr = fdir_frames / f"r{i:02d}-01.png"
                    pg.locator(".slide").screenshot(path=str(fr))
                    frames.append((fr, item[1]))
                else:
                    words = pg.evaluate(GROUPS_JS)
                    kind_ = pg.evaluate("document.querySelector('.slide').dataset.kind")
                    if kind_ == "family" and i == 1: holds = holds_for(words, open_family["budget"], open_family["final"])
                    else: holds = holds_for(words, budget.get(kind_, 6))
                    for k in range(1, len(words) + 1):
                        pg.evaluate(SHOW_JS, k)
                        fr = fdir_frames / f"r{i:02d}-{k:02d}.png"
                        pg.locator(".slide").screenshot(path=str(fr))
                        frames.append((fr, holds[k-1]))
                    if kind_ == "hook" and not any(f.endswith("-reel-cover.png") for f in files):
                        name = f"{stem}-reel-cover.png"
                        pg.locator(".slide").screenshot(path=str(out / name)); files.append(name)
                tmp.unlink(); pg.close()
        b.close()
    if only is None and post["format"] == "update":
        shutil.copyfile(out / f"{stem}-01.png", out / f"{stem}-reel-cover.png"); files.append(f"{stem}-reel-cover.png")
    if frames:
        lst = fdir_frames / "list.txt"
        lines = []
        for fr, d in frames: lines += [f"file '{fr.resolve()}'", f"duration {d}"]
        lines.append(f"file '{frames[-1][0].resolve()}'")
        lst.write_text("\n".join(lines) + "\n")
        exact = sum(d for _, d in frames)
        # The repeated last entry is for ffmpeg versions that drop the final duration; others hold it twice.
        # -t caps the output at the planned length either way.
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", str(lst),
                        "-vf", "fps=30,format=yuv420p", "-c:v", "libx264", "-preset", "veryfast", "-crf", "18",
                        "-t", f"{exact:.3f}", "-movflags", "+faststart", str(out / f"{stem}-reel.mp4")], check=True)
        files.append(f"{stem}-reel.mp4")
        print(f"reel: {len(frames)} steps, {round(exact, 1)} s")
    (out / "checks.json").write_text(json.dumps({"files": files, "problems": problems}, indent=2))
    if problems:
        print("RENDER CHECK FAILED (shorten copy, never shrink type):"); [print(" -", x) for x in problems]; sys.exit(1)
    print("OK"); [print(" ", f) for f in files]

if __name__ == "__main__":
    main()
