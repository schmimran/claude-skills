def holds_for(words, budget, final=2.0):
    floor = 0.8
    spread = max(budget - final, floor * len(words))
    tot = sum(words) or 1
    hs = [max(floor, spread * w / tot) for w in words]
    hs[-1] += final
    return [round(h, 2) for h in hs]

