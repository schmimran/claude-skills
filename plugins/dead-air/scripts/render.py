#!/usr/bin/env python3
"""Schmim Knews · Dead Air renderer (v2, amber-on-black design system).

Usage:
  python3 render-v2.py <post.json> <design_dir> <out_dir> [--fonts <dir>]

  design_dir  folder holding project/tokens.json and project/components/bundle.css,
              as saved by an Artifact `read` of the "Schmim Knews" design system.
  fonts       folder holding the @fontsource packages (big-shoulders-display,
              work-sans, ibm-plex-mono). Default: ./node_modules/@fontsource.

Formats: single | bundle | weekly | deep | update.
Writes the carousel PNGs (1080x1350), reel.mp4 (the lead story as a deep dive, each line
revealed in turn, about 44 s, 1080x1350, no audio), reel-cover.png and checks.json. Exits 1 on any failed
check (copy rules or overflow). Fix the copy and re-run; never shrink type.
"""
import html, json, os, re, subprocess, sys
from pathlib import Path

OUTLETS = ["NYT", "WaPo", "WSJ", "AP", "Reuters", "CNN", "ABC", "NBC", "CBS", "Fox", "NPR"]
OUTLET_NAMES = {  # names an `us` sentence may use for an unchecked outlet
    "NYT": ["NYT", "New York Times", "the Times"], "WaPo": ["WaPo", "Washington Post"],
    "WSJ": ["WSJ", "Wall Street Journal"], "AP": ["AP", "Associated Press"],
    "Reuters": ["Reuters"], "CNN": ["CNN"], "ABC": ["ABC"], "NBC": ["NBC"],
    "CBS": ["CBS"], "Fox": ["Fox"], "NPR": ["NPR"],
}
STATES = {"silent", "broke", "ran", "unchecked"}
ASKS = ["Follow for the next one.", "Send this to someone who reads the Times.", "Save this. Check back in a week."]
BUNDLE_HOOKS = ["3 US stories. 11 US outlets. Dead air.", "This week's dead air.", "3 things they ran abroad. 0 ran here."]
METHOD = ("Counts as reported abroad at 3+ major foreign outlets; counts as missing at home when none of the "
          "11 major US outlets ran it, not counting whoever broke it. Board: news.schmim.com")
BANNED = [r"\bfr\b", r"\blowkey\b", r"\bno cap\b", r"it'?s giving", r"the girls who", r"\bnot \w+ doing\b",
          r"wake up", r"mainstream media", r"they don'?t want you to know", r"\bamid\b", r"\bsparks?\b",
          r"\bslams?\b", r"in the wake of", r"\bunderscores?\b", r"\breportedly\b", r"\ballegedly\b", r"\breceipts?\b"]
HOOK_BANNED = [r"according to", r"\breportedly\b", r"\ballegedly\b", r"\breceipts?\b"]
EMOJI = re.compile("[\U0001F300-\U0001FAFF☀-➿\U0001F000-\U0001F2FF]")
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()

def esc(s):
    # keep "Oct 12–26" and "Sep 16, 2026" from splitting across lines
    t = html.escape(s or "", quote=True)
    t = re.sub(r"(\d)–(\d)", "\\1\u2060–\u2060\\2", t)
    return re.sub(r"\b(" + "|".join(MONTHS) + r") (\d)", "\\1\u00a0\\2", t)

def nice_date(iso, year=True):
    y, m, d = (int(x) for x in iso.split("-"))
    return f"{MONTHS[m-1]} {d} {y}" if year else f"{MONTHS[m-1]} {d}"

# ---------- tokens.json -> CSS custom properties (tokens.css is generated by the DS page, not served) ----------
def tokens_css(tokens):
    out = [":root{"]
    for t in tokens["color"]["tokens"]:
        v = t["value"]
        if isinstance(v, dict): v = next(iter(v.values()))
        out.append(f"--{t['name']}:{v};")
    for k, v in tokens["type"]["families"].items():
        out.append(f"--font-{k}:{v};")
    for fam, body in tokens.items():
        if fam in ("color", "type", "name", "version") or not isinstance(body, dict): continue
        for t in body.get("tokens", []):
            out.append(f"--{t['name']}:{t['value']};")
    out.append("}")
    return "".join(out)

def fonts_css(fdir):
    faces = [("Big Shoulders Display", "big-shoulders-display", [800, 900]),
             ("Work Sans", "work-sans", [400, 600]),
             ("IBM Plex Mono", "ibm-plex-mono", [400, 500, 600])]
    css = []
    for fam, pkg, weights in faces:
        for w in weights:
            for sub in ("latin", "latin-ext"):
                f = Path(fdir) / pkg / "files" / f"{pkg}-{sub}-{w}-normal.woff2"
                if f.exists():
                    css.append(f"@font-face{{font-family:'{fam}';font-weight:{w};font-style:normal;"
                               f"src:url('{f.resolve().as_uri()}') format('woff2');}}")
    if not css: raise SystemExit(f"no font files under {fdir}; npm i @fontsource/big-shoulders-display @fontsource/work-sans @fontsource/ibm-plex-mono")
    return "".join(css)

# ---------- slide markup (mirrors components/<Name>/preview.html without .frame) ----------
def kicker(segment, right=None):
    r = f'<span class="right">{esc(right)}</span>' if right else ""
    return f'<div class="kicker"><span class="onair"></span><b>Schmim Knews</b><span>{esc(segment)}</span>{r}</div>'

def grid(states, label, style=""):
    cls = {"silent": "", "unchecked": "", "broke": "broke", "ran": "on"}
    sq = "".join(f'<i class="{cls[s]}"></i>' if cls[s] else "<i></i>" for s in states)
    st = f' style="{style}"' if style else ""
    return f'<div class="grid11"{st} aria-label="{esc(label)}">{sq}</div>'

def grid_label(states):
    b, r, u = states.count("broke"), states.count("ran"), states.count("unchecked")
    s = states.count("silent")
    parts = []
    if b: parts.append(f"{b} broke it")
    if r: parts.append(f"{r} ran it")
    parts.append(f"{s} silent")
    if u: parts.append(f"{u} not checked")
    return "11 outlets: " + ", ".join(parts)

def foot(right=None, cue=None, wordmark=False):
    if wordmark: r = '<span class="wordmark">Schmim Knews</span>'
    elif cue: r = f'<span class="cue">{esc(cue)}</span>'
    elif right: r = f"<span>{esc(right)}</span>"
    else: r = ""
    return f'<div class="foot"><span class="handle">@schmimknews</span>{r}</div>'

def hook_slide(st, date, flash, segment="Dead Air"):
    size = "m" if flash else "l"
    return (f'<section class="slide slide--hook{" slide--flash" if flash else ""}" data-kind="hook">'
            f'{kicker(f"{segment} · {nice_date(date)}")}'
            f'<h1 class="hook hook--{size}" data-r data-maxlines="{4 if flash else 3}">{esc(st["headline"])}</h1>'
            f'<p class="stat" data-r data-maxlines="2">{esc(st["stat"])}</p>'
            f'<div class="proof" data-r>{grid(st["grid"], grid_label(st["grid"]))}'
            f'<p class="meta" style="margin-top:24px">{esc(st["meta"])}</p></div>'
            f'{foot(right="news.schmim.com") if segment == "Update" else foot(cue="Swipe →")}</section>')

def receipt_slide(st, segment="Dead Air", small=None, show_topic=True):
    conf = st["confidence"]; on = {"Verified": 3, "Probable": 2}.get(conf, 1)
    meter = "".join('<i class="on"></i>' if i < on else "<i></i>" for i in range(3))
    chips = "".join(f'<span class="outlet">{esc(o["name"])}<small>{esc(o["country"])}</small></span>' for o in st["abroad"])
    chips += "".join(f'<span class="outlet small">{esc(o["name"])}<small>{esc(o.get("country","US · not counted"))}</small></span>' for o in (small or []))
    return (f'<section class="slide" data-kind="receipt">{kicker(segment, st["topic"] if show_topic else None)}'
            f'<div data-r><p class="lede" data-maxlines="4">{esc(st["claim"])}</p>'
            f'<p class="meta" style="margin-top:16px">{esc(st["dateline"])}</p></div>'
            f'<div data-r><p class="label">Ran it abroad</p><div class="outlets">{chips}</div></div>'
            f'<div class="panel" data-r><p class="label" style="margin-bottom:0">The 11 major US outlets</p>'
            f'{grid(st["grid"], grid_label(st["grid"]))}<p class="body" data-maxlines="3">{esc(st["us"])}</p></div>'
            f'<div class="status" data-r><span class="meter" aria-label="confidence {on} of 3">{meter}</span>'
            f'{esc(conf)} · {st["days_dark"]} days dark</div>{foot(right="news.schmim.com")}</section>')

def bundle_slide(post, flash):
    seg = (f"Dead Air · Week of {nice_date(post['date'], False)}" if post["format"] == "weekly"
           else f"Dead Air · {nice_date(post['date'])}")
    items = "".join(f'<li data-r><span class="num">{i+1:02d}</span><div><p class="t" data-maxlines="2">{esc(s["title"])}</p>'
                    f'<p class="meta m" data-maxlines="1">{esc(s["count"])}</p></div></li>' for i, s in enumerate(post["stories"]))
    return (f'<section class="slide{" slide--flash" if flash else ""}" data-kind="bundle">{kicker(seg)}'
            f'<h1 class="hook hook--m" data-r data-maxlines="3">{esc(post["bundle_hook"])}</h1>'
            f'<ol class="stories">{items}</ol>{foot(cue="Swipe →")}</section>')

def closer_slide(ask):
    return ('<section class="slide" data-kind="closer">' + kicker("How we check") +
            '<h1 class="hook hook--m" data-r>Not censorship. Omission.</h1><hr class="rule">'
            '<div style="display:flex;flex-direction:column;gap:24px">'
            '<p class="body" data-r><b>Abroad</b> counts when three or more major foreign outlets run it.</p>'
            '<p class="body" data-r><b>At home</b> counts as missing when none of the 11 major US outlets has run it, not counting the one that broke it.</p>'
            '<p class="body" data-r><b>Every claim is dated.</b> If the status changes, we say so, in a post.</p></div>'
            '<div class="hatch" role="presentation"></div>'
            f'<p class="stat" data-r>{esc(ask)}</p>'
            '<p class="meta" data-r="+">Full board, every story, every check: news.schmim.com</p>'
            + foot(wordmark=True) + '</section>')

def timeline_slide(d):
    key = ' class="key"'
    lis = "".join(f'<li data-r{key if e.get("key") else ""}><span class="d">{esc(e["d"])}</span><p class="e">{esc(e["e"])}</p></li>' for e in d["timeline"])
    return (f'<section class="slide" data-kind="timeline">{kicker("Deep dive · 01 What happened")}'
            f'<p class="lede" data-r>{esc(d["timeline_lede"])}</p><ol class="tl">{lis}</ol>'
            f'<div class="unknown" data-r><p>{esc(d["timeline_note"])}</p></div>{foot(cue="Both sides →")}</section>')

def claims_slide(d):
    lis = "".join(f'<li data-r><span class="who">{esc(c["who"])}<small>{esc(c["src"])}</small></span><p class="say">{esc(c["say"])}</p></li>' for c in d["claims"])
    return (f'<section class="slide" data-kind="claims">{kicker("Deep dive · 02 Both sides")}'
            f'<p class="lede" data-r>What each side says.</p><ul class="claims">{lis}</ul>'
            f'<div class="unknown" data-r><p class="label">Not established</p><p>{esc(d["unknown"])}</p></div>'
            f'{foot(cue="Who ran it →")}</section>')

def family_slide(fm):
    """Optional closing voice: a bereaved family member, built from existing classes (no new styling)."""
    q2 = f'<p class="body" data-r>{esc(fm["quote2"])}</p>' if fm.get("quote2") else ""
    return (f'<section class="slide" data-kind="family">{kicker(fm.get("kicker", "Deep dive · 04 The families"))}'
            f'<h1 class="hook hook--m" data-r data-maxlines="4">{esc(fm["quote"])}</h1>'
            f'<p class="lede" data-r data-maxlines="4">{esc(fm["who"])}</p>{q2}'
            f'<p class="meta" data-r="+">{esc(fm["src"])}</p>{foot(cue="Swipe →")}</section>')

def deep_slides(st, dd, date, ask):
    sl = [hook_slide(st, date, True, "Deep dive"), timeline_slide(dd), claims_slide(dd),
          receipt_slide(st, "Deep dive · 03 Who ran it", dd.get("us_small"), show_topic=False)]
    fm = dd.get("family")
    if fm and fm.get("open"): return [sl[0], family_slide(fm)] + sl[1:] + [closer_slide(ask)]
    if fm: sl.append(family_slide(fm))
    return sl + [closer_slide(ask)]

def reel_order(sl, dd):
    """A family block marked open leads the Reel, before the hook (Imran, Oct 31); the carousel keeps the hook as its cover."""
    fm = dd.get("family") or {}
    return [sl[1], sl[0]] + sl[2:] if fm.get("open") else sl

def reel_slides(post):
    """Every post's Reel is a deep dive on its lead story, revealed line by line (Imran, Oct 31)."""
    if post["format"] == "update": return []
    if post["format"] == "deep": return reel_order(build_slides(post), post["deep"])
    rl = post["reel"]
    return reel_order(deep_slides(rl["story"], rl["deep"], post["date"], post["ask"]), rl["deep"])

def build_slides(post):
    f, flash, d = post["format"], post.get("flash", False), post["date"]
    S = post["stories"]
    if f == "single": return [hook_slide(S[0], d, flash), receipt_slide(S[0]), closer_slide(post["ask"])]
    if f in ("bundle", "weekly"):
        return ([bundle_slide(post, flash)] + [receipt_slide(s, f"Dead Air · {i+1} of {len(S)}") for i, s in enumerate(S)]
                + [closer_slide(post["ask"])])
    if f == "deep":
        dd = post["deep"]
        return deep_slides(S[0], dd, d, post["ask"])
    if f == "update": return [hook_slide(S[0], d, flash, "Update")]
    raise SystemExit(f"unknown format {f}")

# ---------- copy checks (run before rendering) ----------
NUMWORDS = "zero one two three four five six seven eight nine ten eleven".split()

def stat_errors(s):
    """The count line must be plain English a stranger understands, and literally true of the grid."""
    g, st, errs = s["grid"], s["stat"], []
    sil = g.count("silent")
    if re.search(r"we could check|of the \d+|: nothing", st, re.I):
        errs.append(f"stat '{st}' uses the old insider phrasing; write a sentence, e.g. 'Reuters reported it. Nine other major US outlets didn't.'")
    nums = {str(sil), NUMWORDS[sil]} | ({"none", "no "} if sil == 11 else set())
    if not any(re.search(r"\b" + re.escape(n.strip()) + r"\b", st, re.I) for n in nums):
        errs.append(f"stat '{st}' must state the silent count ({sil}) as a number or word")
    for idx, state in enumerate(g):
        if state == "broke" and not any(nm.lower() in st.lower() for nm in OUTLET_NAMES[OUTLETS[idx]] + ["Washington Post", "New York Times"]):
            errs.append(f"stat must name the outlet that broke it ({OUTLETS[idx]})")
    return errs

def check_copy(post):
    errs = []
    f = post["format"]
    n = {"single": 1, "deep": 1, "update": 1, "bundle": 3, "weekly": 3}[f]
    if len(post["stories"]) != n: errs.append(f"{f} needs {n} stories, got {len(post['stories'])}")
    if f in ("bundle", "weekly") and post.get("bundle_hook") not in BUNDLE_HOOKS:
        errs.append(f"bundle_hook must be one of {BUNDLE_HOOKS}")
    if f != "update" and post.get("ask") not in ASKS: errs.append(f"ask must be one of {ASKS}")
    items = [(f"story {i+1}", s, f) for i, s in enumerate(post["stories"])]
    if f not in ("update", "deep"):
        if "reel" not in post: errs.append("every post needs `reel` {story, deep}: the lead story as a deep dive")
        else: items.append(("reel story", post["reel"]["story"], "deep"))
    outer_f = f
    for tag, s, f in items:
        g = s["grid"]
        if len(g) != 11 or set(g) - STATES: errs.append(f"{tag}: grid must be 11 of {STATES}"); continue
        if s["confidence"] not in ("Verified", "Probable"): errs.append(f"{tag}: {s['confidence']} never posts")
        sil, ran, unc = g.count("silent"), g.count("ran"), g.count("unchecked")
        if f != "update" and ran: errs.append(f"{tag}: a Flagged story can't have a 'ran' square (use format update)")
        if f != "update": errs += [f"{tag}: {e}" for e in stat_errors(s)]
        for idx, st in enumerate(g):
            if st == "unchecked" and not any(nm in s["us"] for nm in OUTLET_NAMES[OUTLETS[idx]]):
                errs.append(f"{tag}: {OUTLETS[idx]} is unchecked but not named in `us`")
        if f in ("single", "deep", "update"):
            w = len(s["headline"].split())
            if not 5 <= w <= 14 and f != "update": errs.append(f"{tag}: headline has {w} words (5-14; the 3-line cap usually means 10 or fewer)")
            for p in HOOK_BANNED:
                if re.search(p, s["headline"], re.I): errs.append(f"{tag}: headline uses '{p}'")
        if f in ("bundle", "weekly"):
            w = len(s["title"].split())
            if not 6 <= w <= 11: errs.append(f"{tag}: bundle title has {w} words (6-11)")
        if not 3 <= len(s["abroad"]) <= 5: errs.append(f"{tag}: abroad needs 3-5 outlets")
        if len(s.get("topic", "")) > 14: errs.append(f"{tag}: topic '{s.get('topic')}' over 14 characters (kicker must stay on one line)")
        if len(re.findall(r"[.!?](\s|$)", s["us"])) > 2: errs.append(f"{tag}: `us` is more than two sentences")
    f = outer_f
    texts = json.dumps(post, ensure_ascii=False)
    for p in BANNED:
        if re.search(p, texts, re.I): errs.append(f"voice: banned phrase /{p}/")
    if EMOJI.search(texts): errs.append("voice: emoji found")
    cap = post.get("caption", "")
    if f != "update" or cap:
        lines = cap.split("\n")
        if len(lines[0]) > 125: errs.append(f"caption line 1 is {len(lines[0])} chars (125 max)")
        if "#" in lines[0] or re.search(r"\d{4}", lines[0]) or re.search(r"\b(" + "|".join(MONTHS) + r")\w* \d", lines[0]):
            errs.append("caption line 1 must have no hashtag and no date")
        if METHOD not in cap: errs.append("caption is missing the fixed method sentence")
        tags = re.findall(r"#\w+", cap)
        if not {"#DeadAir", "#SchmimKnews"} <= set(tags) or not 3 <= len(tags) <= 5:
            errs.append(f"caption hashtags must be #DeadAir #SchmimKnews + 1-3 subject tags (got {tags})")
        if f != "update" and post.get("ask") not in cap: errs.append("caption must carry the same ask as the Closer")
    # Every caption block ends with the post's sources (Imran, Oct 31): "Sources" on its own line, then the list.
    src = (post.get("sources") or "").strip()
    if not src: errs.append("post needs `sources`: one line, outlet (date); outlet (date); ...")
    for key in ("caption", "reel_caption"):
        c = post.get(key, "")
        if not c: continue
        if src and not c.endswith("\n\nSources\n" + src): errs.append(f"{key} must end with a blank line, 'Sources', then the `sources` line")
        if len(c) > 2200: errs.append(f"{key} is {len(c)} chars (Instagram max 2200)")
    return errs

# ---------- render ----------
MEASURE_JS = r"""
() => {
  const out = [];
  const s = document.querySelector('.slide');
  const r = s.getBoundingClientRect();
  const cs = getComputedStyle(s);
  const padB = parseFloat(cs.paddingBottom);
  const limit = r.bottom - (s.classList.contains('slide--reel') ? padB : 0);
  if (s.scrollHeight > s.clientHeight + 1) out.push('content taller than the canvas');
  const f = s.querySelector('.foot');
  if (f && f.getBoundingClientRect().bottom > limit + 1) out.push('footer pushed past its line');
  s.querySelectorAll('[data-maxlines]').forEach(el => {
    const lh = parseFloat(getComputedStyle(el).lineHeight);
    const lines = Math.round(el.getBoundingClientRect().height / lh);
    if (lines > +el.dataset.maxlines) out.push(`${el.tagName.toLowerCase()}.${el.className} runs ${lines} lines (max ${el.dataset.maxlines}): "${el.textContent.slice(0,60)}"`);
  });
  if (s.classList.contains('slide--reel')) {
    s.querySelectorAll('.kicker, .hook, .stat, .grid11, .foot').forEach(el => {
      const b = el.getBoundingClientRect();
      if (b.top < 250 - 1 || b.bottom > 1920 - 420 + 1) out.push(`reel: ${el.className} outside the safe zone`);
    });
  }
  return out;
}
"""

GROUPS_JS = r"""
() => {
  const els = [...document.querySelectorAll('.slide [data-r]')];
  const groups = [];
  els.forEach(el => { if (el.dataset.r === '+' && groups.length) groups[groups.length-1].push(el); else groups.push([el]); });
  window.__groups = groups;
  return groups.map(g => g.map(e => e.innerText).join(' ').trim().split(/\s+/).filter(Boolean).length);
}
"""
SHOW_JS = "(k) => { window.__groups.forEach((g, i) => g.forEach(e => e.style.visibility = i < k ? 'visible' : 'hidden')); }"

